let LANG =
  localStorage.getItem("cg-lang") ||
  ((navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en");

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/* Engine reasons are a finite set — translate by pattern, else keep original. */
const REASON_PATTERNS = [
  [/^no evidence of type '(.+)' on file$/, "尚无类型为 '$1' 的证据文件"],
  [/^no registration in scheme '(.+)'$/, "尚未在 '$1' 计划完成注册"],
  [/^channel field '(.+)' not filled$/, "渠道字段 '$1' 未填写"],
  [/^product attribute '(.+)' not provided$/, "未提供产品属性 '$1'"],
  [/^rule jurisdiction (\S+) not in market scope$/, "规则法域 $1 不在该市场的法域范围内"],
  [/^applicability condition not met$/, "适用条件未满足"],
  [/^evidence not yet human-reviewed$/, "证据尚未经人工核验"],
  [/^evidence scope does not cover this SKU\/jurisdiction$/, "证据的型号/法域范围不覆盖该 SKU"],
  [/^evidence past its validity date$/, "证据已过有效期"],
  [/^registration not valid for this jurisdiction$/, "该注册对此法域无效"],
  [/^registration lapsed$/, "注册已失效"],
  [/^effective (\S+), evaluated as of (\S+)$/, "生效日期 $1，评估基准日 $2"],
  [/^expired (\S+)$/, "已于 $1 失效"],
  [/^superseded by (.+)$/, "已被 $1 取代"],
  [/^no channel selected$/, "未选择销售渠道"],
  [/^channel rule for (.+)$/, "属于渠道 $1 的规则"],
  [/^product facts insufficient to decide applicability: (.+)$/, "产品事实不足以判定适用性，缺失字段：$1"],
  [/^channel requirement evaluated without a channel$/, "渠道要求在未指定渠道时被评估"],
];

function trReason(reason) {
  if (LANG !== "zh" || !reason) return reason || "";
  for (const [re, tmpl] of REASON_PATTERNS) {
    const m = reason.match(re);
    if (m) return tmpl.replace(/\$(\d)/g, (_, i) => m[+i]);
  }
  return reason;
}

